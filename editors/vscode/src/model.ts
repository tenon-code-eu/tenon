// Conversation model: the thread shown in the chat panel, rebuilt from
// `session/update` notifications. No vscode runtime import, so the unit tests
// run it under plain Node; onDidChange has the shape of a vscode.Event.
import type { ContentBlock, SessionNotification, ToolCallContent } from "@agentclientprotocol/sdk";
import type * as vscode from "vscode";

export type ToolStatus = "pending" | "in_progress" | "completed" | "failed";

/**
 * Provider of the turn's last call, shown as a badge under the answer
 * (`_meta.tenon` of usage_update: providerName or provider, jurisdiction;
 * tenon sends no country, so it stays unset in the extension).
 */
export interface AnswerProvider {
  name: string;
  country?: string;
  jurisdiction?: string;
}

export type Item =
  | { kind: "user"; text: string }
  | { kind: "agent"; text: string; provider?: AnswerProvider }
  | { kind: "thought"; text: string }
  | {
      kind: "tool";
      id: string;
      title: string;
      toolKind: string;
      status: ToolStatus;
      output: string;
      diff?: { path: string; oldText?: string; newText: string };
    }
  | {
      kind: "permission";
      /** Generated by the extension (p1, p2, …), one per request. */
      requestId: string;
      /** The tool item the request is about, when tenon names one. */
      toolCallId?: string;
      title: string;
      options: { optionId: string; name: string; kind: string }[];
      /** optionId of the answer chosen (card or notification). */
      answered?: string;
      /** Answered "cancelled": notification dismissed, Stop, or tenon gone. */
      refused?: boolean;
    };

/** Calls sent to one provider, under one jurisdiction (one per usage_update). */
export interface Send {
  provider: string;
  jurisdiction?: string;
  n: number;
}

export interface Banner {
  kind: "stopped" | "error" | "noFolder";
  text: string;
}

export interface ConversationState {
  sessionId?: string;
  cwd?: string;
  items: Item[];
  busy: boolean;
  commands: { name: string; description: string }[];
  sessions: { sessionId: string; title: string; updatedAt: string }[];
  /** Chips above the input; the blocks themselves stay on the host (Chat). */
  attachments: { id: string; label: string }[];
  meta?: Record<string, unknown>;
  banner?: Banner;
  /** A session/load is in progress: the thread was emptied and its replay is on its way. */
  loading?: boolean;
  /** Context of the last usage_update: `used` input tokens of a `size` window. */
  usage?: { used: number; size: number };
  /** Input and output tokens of the session's calls (`_meta.tenon` of each usage_update). */
  tokens?: { input: number; output: number };
  /** Calls per provider and jurisdiction, one per usage_update (a resumed session's replay included). */
  sends?: Send[];
}

/**
 * Whether the chat shows its home screen: until the first message of the
 * session (tenon's notices, thought items, do not count), never while a turn
 * starts or a session loads, nor under the noFolder or stopped banner.
 */
export function homeVisible(s: ConversationState): boolean {
  const kind = s.banner?.kind;
  if (s.busy || s.loading || kind === "noFolder" || kind === "stopped") {
    return false;
  }
  return s.items.every((i) => i.kind === "thought");
}

/** Minimum interval between two onDidChange events (one animation frame). */
export const CHANGE_INTERVAL_MS = 16;

/** Updates kept while the id of a new session is not known yet. */
const MAX_EARLY = 10_000;

type Listener = (s: ConversationState) => unknown;

/** What session/load replaces, kept to roll back a failed load (with the turn's provider). */
export type Snapshot = Pick<
  ConversationState,
  "sessionId" | "cwd" | "meta" | "items" | "commands" | "usage" | "tokens" | "sends"
> & {
  provider?: AnswerProvider;
};

/** Text of a content block as shown in the thread. */
function blockText(b: ContentBlock): string {
  switch (b.type) {
    case "text":
      return b.text;
    case "resource_link":
      return b.name;
    case "resource":
      return b.resource.uri;
    default:
      return "";
  }
}

function toolOutput(content: ToolCallContent[]): { output: string; diff?: { path: string; oldText?: string; newText: string } } {
  const texts: string[] = [];
  let diff: { path: string; oldText?: string; newText: string } | undefined;
  for (const c of content) {
    if (c.type === "content") {
      const t = blockText(c.content);
      if (t) {
        texts.push(t);
      }
    } else if (c.type === "diff") {
      diff = { path: c.path, newText: c.newText };
      if (typeof c.oldText === "string") {
        diff.oldText = c.oldText;
      }
    }
  }
  return diff ? { output: texts.join("\n"), diff } : { output: texts.join("\n") };
}

function nonEmpty(v: unknown): string | undefined {
  return typeof v === "string" && v !== "" ? v : undefined;
}

/**
 * The meta after a usage_update (`_meta.tenon` of the call): a new provider
 * (fallback) replaces provider, providerName and jurisdiction together, so
 * the old jurisdiction never stays on a new provider; the same provider only
 * gets the fields sent. undefined: nothing changes.
 */
function usageMeta(meta: Record<string, unknown>, t: Record<string, unknown>): Record<string, unknown> | undefined {
  const provider = nonEmpty(t.provider);
  if (!provider) {
    return undefined;
  }
  const name = nonEmpty(t.providerName);
  const jurisdiction = nonEmpty(t.jurisdiction);
  const next: Record<string, unknown> = { ...meta, provider };
  if (provider !== meta.provider) {
    delete next.providerName;
    delete next.jurisdiction;
  }
  if (name) {
    next.providerName = name;
  }
  if (jurisdiction) {
    next.jurisdiction = jurisdiction;
  }
  const same = ["provider", "providerName", "jurisdiction"].every((k) => next[k] === meta[k]);
  return same ? undefined : next;
}

/** The answer badge of a usage_update's `_meta.tenon`; undefined without a provider. */
function usageProvider(t: Record<string, unknown>): AnswerProvider | undefined {
  const name = nonEmpty(t.providerName) ?? nonEmpty(t.provider);
  if (!name) {
    return undefined;
  }
  const jurisdiction = nonEmpty(t.jurisdiction);
  return jurisdiction ? { name, jurisdiction } : { name };
}

function sameProvider(a: AnswerProvider | undefined, b: AnswerProvider): boolean {
  return a !== undefined && a.name === b.name && a.country === b.country && a.jurisdiction === b.jurisdiction;
}

export class Conversation {
  state: ConversationState = { items: [], busy: false, commands: [], sessions: [], attachments: [] };

  private readonly listeners = new Set<Listener>();
  private timer: ReturnType<typeof setTimeout> | undefined;
  private early: SessionNotification[] = [];
  /** Provider of the current turn's last call (badge of its new answers). */
  private provider: AnswerProvider | undefined;
  /** Token of the latest session/load (startLoading). */
  private loads = 0;

  /** Fires with the whole state, at most once per CHANGE_INTERVAL_MS. */
  readonly onDidChange: vscode.Event<ConversationState> = (listener, thisArgs?: unknown, disposables?) => {
    const l: Listener = (s) => listener.call(thisArgs, s);
    this.listeners.add(l);
    const d = { dispose: () => this.listeners.delete(l) };
    if (Array.isArray(disposables)) {
      disposables.push(d);
    }
    return d;
  };

  /**
   * Switches to sessionId (clearing the thread), or to "no session yet" when
   * sessionId is undefined: updates that arrive before the id is known are
   * kept and applied by the next begin() if they belong to that session.
   */
  begin(sessionId: string | undefined, cwd: string | undefined, meta?: Record<string, unknown>): void {
    const early = this.early;
    this.early = [];
    this.state.sessionId = sessionId;
    this.state.cwd = cwd;
    this.state.meta = meta;
    this.state.items = [];
    this.state.commands = [];
    this.state.usage = undefined;
    this.state.tokens = undefined;
    this.state.sends = [];
    this.provider = undefined;
    if (sessionId !== undefined) {
      for (const n of early) {
        if (n.sessionId === sessionId) {
          this.apply(n);
        }
      }
    }
    this.changed();
  }

  snapshot(): Snapshot {
    const { sessionId, cwd, meta, items, commands, usage, tokens, sends } = this.state;
    // sends are counted in place: the snapshot keeps its own copy.
    return { sessionId, cwd, meta, items, commands, usage, tokens, sends: sends?.map((x) => ({ ...x })), provider: this.provider };
  }

  /** Puts back a snapshot (a failed session/load); buffered updates are dropped. */
  restore(s: Snapshot): void {
    this.early = [];
    const { provider, ...state } = s;
    this.provider = provider;
    Object.assign(this.state, state);
    this.changed();
  }

  /**
   * A session/load starts (no home screen meanwhile); the token returned
   * ends it. Loads may overlap: only the latest one's end clears the flag.
   */
  startLoading(): number {
    const token = ++this.loads;
    if (!this.state.loading) {
      this.state.loading = true;
      this.changed();
    }
    return token;
  }

  /** The load of token is over; no effect when a newer load started since. */
  endLoading(token: number): void {
    if (token === this.loads && this.state.loading) {
      this.state.loading = false;
      this.changed();
    }
  }

  /** Sets the metadata of the current session (`_meta.tenon`). */
  setMeta(meta: Record<string, unknown> | undefined): void {
    this.state.meta = meta;
    this.changed();
  }

  /** Adds an item at the end of the thread (permission cards). */
  addItem(item: Item): void {
    this.state.items.push(item);
    this.changed();
  }

  addUser(text: string): void {
    // A new turn: its answers wait for its own calls.
    this.provider = undefined;
    this.state.items.push({ kind: "user", text });
    this.changed();
  }

  setBusy(busy: boolean): void {
    if (this.state.busy !== busy) {
      this.state.busy = busy;
      this.changed();
    }
  }

  setBanner(banner: Banner | undefined): void {
    this.state.banner = banner;
    this.changed();
  }

  setAttachments(attachments: ConversationState["attachments"]): void {
    this.state.attachments = attachments;
    this.changed();
  }

  setSessions(sessions: ConversationState["sessions"]): void {
    this.state.sessions = sessions;
    this.changed();
  }

  apply(n: SessionNotification): void {
    if (this.state.sessionId === undefined) {
      if (this.early.length < MAX_EARLY) {
        this.early.push(n);
      }
      return;
    }
    if (n.sessionId !== this.state.sessionId) {
      return;
    }
    const u = n.update;
    const items = this.state.items;
    switch (u.sessionUpdate) {
      case "user_message_chunk": {
        // A replayed message comes as one chunk per block (text, then
        // attachments): one bubble, like the live one.
        const text = blockText(u.content);
        const last = items[items.length - 1];
        if (last && last.kind === "user") {
          last.text = last.text && text ? `${last.text}\n${text}` : last.text + text;
        } else {
          this.provider = undefined;
          items.push({ kind: "user", text });
        }
        break;
      }
      case "agent_message_chunk":
      case "agent_thought_chunk": {
        const kind = u.sessionUpdate === "agent_message_chunk" ? "agent" : "thought";
        const text = blockText(u.content);
        const last = items[items.length - 1];
        if (last && last.kind === kind) {
          last.text += text;
        } else if (kind === "agent" && this.provider) {
          items.push({ kind, text, provider: { ...this.provider } });
        } else {
          items.push({ kind, text });
        }
        break;
      }
      case "tool_call": {
        const existing = this.tool(u.toolCallId);
        const out = toolOutput(u.content ?? []);
        const item: Extract<Item, { kind: "tool" }> = {
          kind: "tool",
          id: u.toolCallId,
          title: u.title,
          toolKind: u.kind ?? "other",
          status: u.status ?? "pending",
          ...out,
        };
        if (existing) {
          Object.assign(existing, item);
        } else {
          items.push(item);
        }
        break;
      }
      case "tool_call_update": {
        let item = this.tool(u.toolCallId);
        if (!item) {
          item = { kind: "tool", id: u.toolCallId, title: u.toolCallId, toolKind: "other", status: "pending", output: "" };
          items.push(item);
        }
        if (u.title) {
          item.title = u.title;
        }
        if (u.kind) {
          item.toolKind = u.kind;
        }
        if (u.status) {
          item.status = u.status;
        }
        if (u.content) {
          const out = toolOutput(u.content);
          item.output = out.output;
          if (out.diff) {
            item.diff = out.diff;
          }
        }
        break;
      }
      case "available_commands_update":
        this.state.commands = u.availableCommands.map((c) => ({ name: c.name, description: c.description }));
        break;
      case "usage_update": {
        // The session view's gauge, whatever the agent.
        if (typeof u.used === "number" && typeof u.size === "number") {
          this.state.usage = { used: u.used, size: u.size };
        }
        const t = u._meta?.tenon;
        if (typeof t !== "object" || t === null) {
          break;
        }
        const tenon = t as Record<string, unknown>;
        this.count(tenon);
        const p = usageProvider(tenon);
        this.badgeTurn(p);
        if (p) {
          this.addSend(p);
        }
        const meta = this.state.meta;
        const next = meta ? usageMeta(meta, tenon) : undefined;
        if (next) {
          this.state.meta = next;
        }
        break;
      }
      case "session_info_update": {
        const s = this.state.sessions.find((x) => x.sessionId === n.sessionId);
        if (!s) {
          return;
        }
        if (typeof u.title === "string") {
          s.title = u.title;
        }
        if (typeof u.updatedAt === "string") {
          s.updatedAt = u.updatedAt;
        }
        break;
      }
      default:
        return;
    }
    this.changed();
  }

  /**
   * Schedules one onDidChange CHANGE_INTERVAL_MS from now unless one is
   * already pending: every change of the window goes out in that one event,
   * and two events are always at least CHANGE_INTERVAL_MS apart.
   */
  changed(): void {
    if (this.timer !== undefined) {
      return;
    }
    this.timer = setTimeout(() => {
      this.timer = undefined;
      for (const l of [...this.listeners]) {
        l(this.state);
      }
    }, CHANGE_INTERVAL_MS);
  }

  /**
   * A call of the current turn ended on provider p: the turn's answers so
   * far (since the last user message) take it, and so do its next ones
   * (the badge shows the turn's last call). True when an item changed.
   */
  private badgeTurn(p: AnswerProvider | undefined): boolean {
    if (!p) {
      return false;
    }
    this.provider = p;
    let changed = false;
    const items = this.state.items;
    for (let i = items.length - 1; i >= 0; i--) {
      const it = items[i];
      if (it.kind === "user") {
        break;
      }
      if (it.kind === "agent" && !sameProvider(it.provider, p)) {
        it.provider = { ...p };
        changed = true;
      }
    }
    return changed;
  }

  /** Adds the call's input and output tokens to the session's. */
  private count(t: Record<string, unknown>): void {
    const num = (v: unknown) => (typeof v === "number" && Number.isFinite(v) && v > 0 ? v : 0);
    const prev = this.state.tokens ?? { input: 0, output: 0 };
    this.state.tokens = { input: prev.input + num(t.input), output: prev.output + num(t.output) };
  }

  /** One more call to p (the session view's sovereignty section). */
  private addSend(p: AnswerProvider): void {
    const sends = (this.state.sends ??= []);
    const same = sends.find((s) => s.provider === p.name && s.jurisdiction === p.jurisdiction);
    if (same) {
      same.n++;
    } else {
      sends.push(p.jurisdiction ? { provider: p.name, jurisdiction: p.jurisdiction, n: 1 } : { provider: p.name, n: 1 });
    }
  }

  /** The diff of a tool item of the thread (what "Open diff" shows). */
  toolDiff(id: string): { path: string; oldText?: string; newText: string } | undefined {
    return this.tool(id)?.diff;
  }

  private tool(id: string): Extract<Item, { kind: "tool" }> | undefined {
    for (let i = this.state.items.length - 1; i >= 0; i--) {
      const it = this.state.items[i];
      if (it.kind === "tool" && it.id === id) {
        return it;
      }
    }
    return undefined;
  }
}
